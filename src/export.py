"""
Export functionality for analysis results.

Supports exporting to:
- JSON (machine-readable)
- Markdown (human-readable)
- PDF (professional reports)
"""

import json
from datetime import datetime
from pathlib import Path

from src.logging_config import get_logger

logger = get_logger(__name__)


def export_to_json(data: dict, output_path: str | Path) -> Path:
    """
    Export analysis to JSON file.

    Args:
        data: Analysis data dictionary
        output_path: Path to output file

    Returns:
        Path to created file
    """
    output_path = Path(output_path)
    logger.info("export_json_started", output_path=str(output_path))

    try:
        with output_path.open("w") as f:
            json.dump(data, f, indent=2, default=str)

        logger.info("export_json_complete", output_path=str(output_path))
        return output_path

    except Exception as e:
        logger.error("export_json_failed", error=str(e), exc_info=True)
        raise


def export_to_markdown(data: dict, output_path: str | Path) -> Path:
    """
    Export analysis to Markdown file.

    Args:
        data: Analysis data dictionary
        output_path: Path to output file

    Returns:
        Path to created file
    """
    output_path = Path(output_path)
    logger.info("export_markdown_started", output_path=str(output_path))

    try:
        ticker = data.get("ticker", "UNKNOWN")
        timestamp = data.get("timestamp", datetime.now().isoformat())
        market_snapshot = data.get("market_snapshot", {})
        risk_score = data.get("risk_score", 0)
        ai_analysis = data.get("ai_analysis", "No analysis available")
        sentiment = data.get("sentiment", [])
        news = data.get("news", [])

        # Build markdown content
        md_content = f"""# Analysis Report: {ticker}

**Generated:** {timestamp}
**Risk Score:** {risk_score:.0f}/100

---

## Market Snapshot

| Metric | Value |
|--------|-------|
| Price | ${market_snapshot.get('price', 0):.2f} |
| Volume | {market_snapshot.get('volume', 0):,} |
| 52-Week Volatility | {market_snapshot.get('volatility_52week', 0) * 100:.1f}% |
| Change | {market_snapshot.get('change_percent', 0):.2f}% |

---

## Risk Assessment

"""

        # Risk level
        if risk_score > 70:
            md_content += "🔴 **HIGH RISK** - Elevated volatility detected\n\n"
        elif risk_score > 30:
            md_content += "🟡 **MEDIUM RISK** - Moderate volatility\n\n"
        else:
            md_content += "🟢 **LOW RISK** - Low volatility\n\n"

        md_content += f"Risk Score: **{risk_score:.0f}/100**\n\n"

        # Sentiment section
        if sentiment:
            md_content += "---\n\n## Analyst Sentiment\n\n"
            md_content += "| Firm | Action | Grade |\n"
            md_content += "|------|--------|-------|\n"

            for rating in sentiment[:10]:  # Limit to 10
                firm = rating.get("firm", "Unknown")
                action = rating.get("action", "main").upper()
                grade = rating.get("grade", "N/A")

                # Add emoji based on action
                if action == "UP":
                    emoji = "🟢"
                elif action == "DOWN":
                    emoji = "🔴"
                else:
                    emoji = "🟡"

                md_content += f"| {firm} | {emoji} {action} | {grade} |\n"

            md_content += "\n"

        # News section
        if news:
            md_content += "---\n\n## Recent News\n\n"
            for i, article in enumerate(news[:5], 1):
                title = article.get("title", "No title")
                publisher = article.get("publisher", "Unknown")
                link = article.get("link", "")

                if link:
                    md_content += f"{i}. [{title}]({link}) - *{publisher}*\n"
                else:
                    md_content += f"{i}. {title} - *{publisher}*\n"

            md_content += "\n"

        # AI Analysis
        md_content += "---\n\n## AI Analysis\n\n"
        md_content += f"{ai_analysis}\n\n"

        # Footer
        md_content += "---\n\n"
        md_content += "*Generated by MCPFolio v0.2.0*\n"
        md_content += f"*Report Date: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}*\n"

        # Write to file
        with output_path.open("w") as f:
            f.write(md_content)

        logger.info("export_markdown_complete", output_path=str(output_path))
        return output_path

    except Exception as e:
        logger.error("export_markdown_failed", error=str(e), exc_info=True)
        raise


def export_to_pdf(data: dict, output_path: str | Path) -> Path:
    """
    Export analysis to PDF file.

    Note: Requires reportlab package.
    For now, this converts to markdown and saves as .md
    Future: Implement proper PDF generation with charts

    Args:
        data: Analysis data dictionary
        output_path: Path to output file

    Returns:
        Path to created file
    """
    output_path = Path(output_path)
    logger.info("export_pdf_started", output_path=str(output_path))

    try:
        # For now, export as markdown
        # TODO: Implement proper PDF generation with reportlab
        md_path = output_path.with_suffix(".md")
        export_to_markdown(data, md_path)

        logger.warning(
            "pdf_export_not_implemented",
            message="Exported as markdown instead",
            output_path=str(md_path),
        )

        return md_path

    except Exception as e:
        logger.error("export_pdf_failed", error=str(e), exc_info=True)
        raise


def export_analysis(data: dict, output_path: str | Path, format: str = "json") -> Path:
    """
    Export analysis to file in specified format.

    Args:
        data: Analysis data dictionary
        output_path: Path to output file
        format: Export format (json, markdown, pdf)

    Returns:
        Path to created file

    Raises:
        ValueError: If format is not supported
    """
    format = format.lower()
    logger.info("export_analysis", format=format, output_path=str(output_path))

    if format == "json":
        return export_to_json(data, output_path)
    elif format in ("markdown", "md"):
        return export_to_markdown(data, output_path)
    elif format == "pdf":
        return export_to_pdf(data, output_path)
    else:
        raise ValueError(f"Unsupported export format: {format}")
